def seed(db: Session, reviewer: str) -> bool:
    """Loads demo data if the database is empty. `reviewer` (an email) owns the seeded review inbox."""
    if db.scalar(select(Cde).limit(1)):
        return False
    db.add_all(
        Cde(
            id=c[0],
            name=c[1],
            domain=c[2],
            owner=c[3],
            former_owner=c[4],
            steward=c[5],
            lineage_pct=c[6],
            classification=c[7],
            attested=c[8],
        )
        for c in CDES
    )
    db.add_all(DqRule(id=r[0], name=r[1], cde_id=r[2], dimension=r[3], threshold=r[4], last_value=r[5]) for r in RULES)
    db.add_all(
        Issue(id=i[0], rule_id=i[1], cde_id=i[2], severity=i[3], owner=i[4], opened=i[5], due=i[6], status=i[7], note=i[8])
        for i in ISSUES
    )
    for rp in REPORTS:
        db.add(
            Report(
                id=rp["id"],
                name=rp["name"],
                regulation=rp["regulation"],
                cadence=rp["cadence"],
                owner=rp["owner"],
                cde_ids=rp["cde_ids"],
                principles=rp["principles"],
            )
        )
        db.flush()
        db.add_all(
            LineageNode(
                id=n[0],
                report_id=rp["id"],
                label=n[1],
                sub=n[2],
                col=n[3],
                row=n[4],
                is_report=n[5],
                is_euc=n[6],
                owner=n[7],
                cde_ids=n[8],
                controls=n[9],
            )
            for n in rp["nodes"]
        )
        db.add_all(
            LineageEdge(report_id=rp["id"], source=e[0], target=e[1], kind=e[2] if len(e) > 2 else "auto") for e in rp["edges"]
        )
    db.add_all(
        Asset(
            name=a[0],
            platform=a[1],
            domain=a[2],
            owner=a[3],
            former_owner=a[4],
            steward=a[5],
            classification=a[6],
            certified=a[7],
            term=a[8],
            cde_ids=a[9],
            usage=a[10],
        )
        for a in ASSETS
    )
    db.add_all(
        GlossaryTerm(
            term=g[0], definition=g[1], owner=g[2], status=g[3], version=g[4], proposed_change=g[5], proposed_definition=g[6]
        )
        for g in GLOSSARY
    )
    db.add_all(Scan(id=s[0], column_name=s[1], dataset=s[2], label=s[3], confidence=s[4], status=s[5]) for s in SCANS)
    db.add_all(Policy(id=p[0], name=p[1], rule=p[2], scope=p[3], mode=p[4]) for p in POLICIES)
    db.add_all(Campaign(id=c[0], name=c[1], type=c[2], due=c[3], total=c[4], others_done=c[5]) for c in CAMPAIGNS)
    db.flush()
    db.add_all(
        ReviewItem(
            id=i[0],
            campaign_id=i[1],
            reviewer=reviewer,
            kind=i[2],
            title=i[3],
            tag=i[4],
            context=i[5],
            recommendation=i[6],
            keep_label=i[7],
            drop_label=i[8],
        )
        for i in ITEMS
    )
    db.add_all(AiModel(**m) for m in MODELS)
    db.flush()
    for ts, actor, action, obj in AUDIT:
        audit.record(db, actor, action, obj, ts=ts)
    db.commit()
    return True
